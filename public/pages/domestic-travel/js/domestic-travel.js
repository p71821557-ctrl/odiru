/* ============================================================
   지도 초기화
   ============================================================ */
function initMap() {
  const container = document.getElementById('kakaoMap');
  map = new kakao.maps.Map(container, {
    center: new kakao.maps.LatLng(36.5, 127.8),
    level: 8
  });
  map.setMinLevel(6);
  map.setMaxLevel(11);
  drawAllRegions();
}

/* ============================================================
   전체 지역 그리기
   ============================================================ */
function drawAllRegions() {
  REGIONS.forEach(region => {
    if (region.isDot) {
      drawDot(region);
    } else {
      region.polygons.forEach((polyCoords, idx) => {
        drawPolygon(region, polyCoords, idx === 0);
      });
    }
    addLabel(region);
  });
}

/* ── 폴리곤 ── */
function drawPolygon(region, coords, isMain) {
  const path = coords.map(([lat, lng]) => new kakao.maps.LatLng(lat, lng));

  const polygon = new kakao.maps.Polygon({
    map,
    path,
    strokeWeight: 1.5,
    strokeColor: '#ffffff',
    strokeOpacity: 0.9,
    fillColor: region.color,
    fillOpacity: 0.42,
    zIndex: 1
  });

  kakao.maps.event.addListener(polygon, 'mouseover', () => {
    if (selectedRegion !== region.name) polygon.setOptions({ fillOpacity: 0.72 });
  });
  kakao.maps.event.addListener(polygon, 'mouseout', () => {
    if (selectedRegion !== region.name) polygon.setOptions({ fillOpacity: 0.42 });
  });
  kakao.maps.event.addListener(polygon, 'click', () => {
    onRegionSelect(region.name);
  });

  drawnPolygons.push({ regionName: region.name, polygon, isDot: false });
}

/* ── 독도 원형 ── */
function drawDot(region) {
  const circle = new kakao.maps.Circle({
    map,
    center: new kakao.maps.LatLng(region.center[0], region.center[1]),
    radius: 4000,
    strokeWeight: 2,
    strokeColor: '#ffffff',
    strokeOpacity: 1,
    fillColor: region.color,
    fillOpacity: 0.85,
    zIndex: 5
  });

  kakao.maps.event.addListener(circle, 'mouseover', () => {
    if (selectedRegion !== region.name) circle.setOptions({ fillOpacity: 1 });
  });
  kakao.maps.event.addListener(circle, 'mouseout', () => {
    if (selectedRegion !== region.name) circle.setOptions({ fillOpacity: 0.85 });
  });
  kakao.maps.event.addListener(circle, 'click', () => {
    onRegionSelect(region.name);
    map.panTo(new kakao.maps.LatLng(region.center[0], region.center[1]));
    map.setLevel(6);
  });

  drawnPolygons.push({ regionName: region.name, polygon: circle, isDot: true });
}

/* ── 라벨 ── */
function addLabel(region) {
  let lat, lng;
  if (region.isDot) {
    lat = region.center[0] + 0.09;
    lng = region.center[1];
  } else {
    // 가장 큰 폴리곤의 중심
    const pts = region.polygons[0];
    lat = pts.reduce((s, p) => s + p[0], 0) / pts.length;
    lng = pts.reduce((s, p) => s + p[1], 0) / pts.length;
  }

  // 라벨 위치 미세 보정
  const offsets = {
    '세종': [0.05, 0], '대전': [-0.1, 0], '광주': [0, 0.05],
    '울산': [0.05, 0.05], '독도': [0.12, 0]
  };
  if (offsets[region.name]) {
    lat += offsets[region.name][0];
    lng += offsets[region.name][1];
  }

  const overlay = new kakao.maps.CustomOverlay({
    map,
    position: new kakao.maps.LatLng(lat, lng),
    content: `<div class="rl" data-r="${region.name}" style="background:${region.color}">${region.name}</div>`,
    yAnchor: 0.5,
    zIndex: 10
  });
}

/* ============================================================
   지역 선택 처리
   ============================================================ */
function onRegionSelect(regionName) {
  selectedRegion = regionName;

  /* 모든 폴리곤 초기화 */
  drawnPolygons.forEach(p => {
    if (p.isDot) p.polygon.setOptions({ fillOpacity: 0.85, strokeWeight: 2 });
    else p.polygon.setOptions({ fillOpacity: 0.42, strokeWeight: 1.5 });
  });

  /* 선택된 지역 강조 */
  drawnPolygons
    .filter(p => p.regionName === regionName)
    .forEach(p => {
      if (p.isDot) p.polygon.setOptions({ fillOpacity: 1, strokeWeight: 3 });
      else p.polygon.setOptions({ fillOpacity: 0.85, strokeWeight: 2.5 });
    });

  /* 라벨 강조 */
  document.querySelectorAll('.rl').forEach(el => {
    el.classList.toggle('rl-on', el.dataset.r === regionName);
  });

  /* 사이드바 업데이트 */
  selRegionEl.classList.add('active');
  selRegionTxt.textContent = regionName;
  updateBtn();
}

/* ============================================================
   라벨 클릭 이벤트 (동적 등록)
   ============================================================ */
document.addEventListener('click', e => {
  const el = e.target.closest('.rl');
  if (!el) return;
  const name = el.dataset.r;
  const region = REGIONS.find(r => r.name === name);
  if (!region) return;
  onRegionSelect(name);
  if (region.isDot) {
    map.panTo(new kakao.maps.LatLng(region.center[0], region.center[1]));
    map.setLevel(6);
  }
});

/* ============================================================
   카테고리
   ============================================================ */
document.querySelectorAll('.cat-tag').forEach(t => {
  t.addEventListener('click', () => {
    t.classList.toggle('on');
    if (t.classList.contains('on')) selectedCats.add(t.dataset.cat);
    else selectedCats.delete(t.dataset.cat);
    updateBtn();
  });
});

function updateBtn() {
  const ok = selectedRegion && selectedCats.size > 0;
  btnGo.disabled = !ok;
  if (ok) {
    selSummary.style.display = 'block';
    summaryRegion.textContent = selectedRegion;
    summaryCats.textContent   = [...selectedCats].join(', ');
  } else {
    selSummary.style.display = 'none';
  }
}

